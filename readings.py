#!/usr/bin/env python3
"""
Correct furigana for compounds a tokeniser reads wrongly.

Janome segments a number away from its counter and then gives the number its
regular reading, so 九時 comes out きゅうじ instead of くじ and 一人 comes out
いちにん instead of ひとり. Japanese counters are irregular in exactly the
places learners need most (time, people, dates, native counters), so these are
listed explicitly and matched before tokenisation.

Longest match wins, so 二十日 is read はつか rather than falling back to
二十 + 日.
"""

